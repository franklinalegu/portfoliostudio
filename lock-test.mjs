import { readFileSync } from "fs";
import assert from "assert";
const src = readFileSync(new URL("./app.js", import.meta.url), "utf8");
assert.ok(!/lockHash: "[^"]+"/.test(src.replace('lockHash: ""', "")), "no seeded hash may ship");
assert.ok(src.includes('lockHash: ""'), "default lockHash must be empty");
for (const s of ["vLock", "tryUnlock", "10 * 60 * 1000", "setInterval(", "api/auth.php", "?action=login", "?action=change-password", "retryAfter"]) assert.ok(src.includes(s), "missing lock: " + s);
assert.ok(!src.includes("setupform"), "no set-password screen may ship");
assert.ok(!src.includes("trySetup"), "no client-side setup path may ship");
assert.ok(!src.includes("vSetup"), "no client-side setup view may ship");
assert.ok(!src.includes("needsSetup"), "login is mandatory on every device");
assert.ok(!src.includes("=== S.settings.lockHash"), "password must be checked by the server, not the client");
assert.ok(!src.includes("remove-lock"), "the studio lock must not be removable");
assert.ok(!src.includes("length < 4"), "no 4 char minimum may remain");
assert.ok(!src.includes("visibilitychange"), "must not instant lock on tab switch");
